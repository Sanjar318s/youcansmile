/* Auto-translate RU → EN / UZ (admin writes Russian only). */
const Translate = (() => {
  const cache = Object.create(null);

  function cacheKey(text, to) {
    return `${to}::${text}`;
  }

  function readLs(key) {
    try {
      return localStorage.getItem('ycs_tr:' + key) || '';
    } catch (_) {
      return '';
    }
  }

  function writeLs(key, val) {
    try {
      localStorage.setItem('ycs_tr:' + key, val);
    } catch (_) {}
  }

  async function mymemory(text, to) {
    const q = String(text || '').trim();
    if (!q) return '';
    if (to === 'ru') return q;
    const key = cacheKey(q, to);
    if (cache[key]) return cache[key];
    const ls = readLs(key);
    if (ls) {
      cache[key] = ls;
      return ls;
    }
    const url =
      'https://api.mymemory.translated.net/get?q=' +
      encodeURIComponent(q.slice(0, 450)) +
      '&langpair=ru|' +
      encodeURIComponent(to);
    const res = await fetch(url);
    if (!res.ok) throw new Error('translate_http');
    const data = await res.json();
    let out = (data && data.responseData && data.responseData.translatedText) || '';
    out = String(out).trim();
    if (!out || /MYMEMORY WARNING|INVALID SOURCE/i.test(out)) {
      throw new Error('translate_bad');
    }
    cache[key] = out;
    writeLs(key, out);
    return out;
  }

  async function one(text, to) {
    const q = String(text || '').trim();
    if (!q) return '';
    try {
      return await mymemory(q, to);
    } catch (_) {
      return q;
    }
  }

  async function text(text, to) {
    const raw = String(text || '');
    if (!raw.trim() || to === 'ru') return raw.trim();
    const lines = raw.split(/\n/);
    const out = [];
    for (const line of lines) {
      if (!line.trim()) {
        out.push('');
        continue;
      }
      out.push(await one(line.trim(), to));
    }
    return out.join('\n');
  }

  async function fromRu(ruText) {
    const ru = String(ruText || '').trim();
    if (!ru) return { ru: '', en: '', uz: '' };
    const [en, uz] = await Promise.all([text(ru, 'en'), text(ru, 'uz')]);
    return { ru, en, uz };
  }

  return { one, text, fromRu };
})();

const I18n = {
  _lang: ['ru', 'uz', 'en'].includes(localStorage.getItem('ycs_lang')) ? localStorage.getItem('ycs_lang') : 'ru',

  get lang() {
    return this._lang;
  },

  setLang(lang) {
    this._lang = ['ru', 'uz', 'en'].includes(lang) ? lang : 'ru';
    localStorage.setItem('ycs_lang', this._lang);
    document.documentElement.lang = this._lang;
  },

  t(key) {
    if (typeof ThemeApply !== 'undefined') {
      const over = ThemeApply.textOverride(key, this._lang);
      if (over) return over;
    }
    const dict = TRANSLATIONS[this._lang] || TRANSLATIONS.ru;
    if (dict[key] !== undefined) return dict[key];
    if (TRANSLATIONS.ru[key] !== undefined) return TRANSLATIONS.ru[key];
    return key;
  },

  txt(obj) {
    if (!obj) return '';
    if (typeof obj === 'string') return obj;
    const lang = this._lang;
    const direct = obj[lang];
    if (direct) return direct;
    const ru = obj.ru || obj.en || obj.uz || '';
    if (!ru || lang === 'ru') return ru;
    // Runtime auto-translate when EN/UZ missing (old products / admin RU-only)
    if (typeof Translate !== 'undefined' && Translate.one) {
      const key = lang + '::' + ru;
      try {
        const ls = localStorage.getItem('ycs_tr:' + key);
        if (ls) return ls;
      } catch (_) {}
      if (!this._pendingTr) this._pendingTr = Object.create(null);
      if (!this._pendingTr[key]) {
        this._pendingTr[key] = true;
        Translate.text(ru, lang)
          .then((out) => {
            if (!out || out === ru) return;
            try {
              localStorage.setItem('ycs_tr:' + key, out);
            } catch (_) {}
            document.dispatchEvent(new CustomEvent('ycs:i18n-ready', { detail: { lang, text: out } }));
          })
          .finally(() => {
            delete this._pendingTr[key];
          });
      }
    }
    return ru;
  },
};

/* применение data-i18n / data-ph-i18n с учётом суффиксов _id / _root / _2 */
function applyI18n(root) {
  const dict = TRANSLATIONS[I18n.lang] || TRANSLATIONS.ru;
  const resolveKey = (key) => {
    if (typeof ThemeApply !== 'undefined') {
      const over = ThemeApply.textOverride(key, I18n.lang);
      if (over) return over;
    }
    if (dict[key] !== undefined) return dict[key];
    if (TRANSLATIONS.ru[key] !== undefined) return TRANSLATIONS.ru[key];
    return undefined;
  };
  const map = (k) => {
    const direct = resolveKey(k);
    if (direct !== undefined) return direct;
    if (k.endsWith('_id')) return resolveKey(k.slice(0, -3));
    if (k.endsWith('_root')) return resolveKey(k.slice(0, -5));
    if (k.endsWith('_2')) return resolveKey(k.slice(0, -2));
    return undefined;
  };
  const base = root || document;
  base.querySelectorAll('[data-i18n]').forEach((el) => {
    const t = map(el.dataset.i18n);
    if (t !== undefined) el.textContent = t;
  });
  base.querySelectorAll('[data-ph-i18n]').forEach((el) => {
    const t = map(el.dataset.phI18n);
    if (t !== undefined) el.placeholder = t;
  });
}
